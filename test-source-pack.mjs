import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { SourceRegistry } from "./source-registry.js";

const pack = JSON.parse(await fs.readFile("source-packs/maldives-core-v1.json", "utf8"));
assert.equal(pack.pack, "maldives-core-v1");
assert.ok(Array.isArray(pack.sources));
assert.ok(pack.sources.length >= 30);
const tempDir = await fs.mkdtemp(path.join(os.tmpdir(), "argus-source-pack-"));
const registry = new SourceRegistry({ storePath: path.join(tempDir, "sources.json") });
await registry.load();
const preview = await registry.import(pack.sources, { dryRun: true });
assert.equal(preview.invalid, 0);
assert.equal(preview.duplicateInImport, 0);
const applied = await registry.import(pack.sources);
assert.equal(applied.created, pack.sources.length);
assert.equal(registry.stats().enabled, pack.sources.length);
assert.ok(registry.list({ collector: "web" }).every((source) => source.collectorConfig?.bootstrapMode === "mark_seen"));
const met = registry.list({ entityId: "mv-met" }).find((source) => source.platform === "web");
assert.ok(met);
assert.equal(met.id, "mv-met-web-6c7d2f71");
assert.equal(met.collectorConfig.discoveryUrl, "https://meteorology.gov.mv/news");
assert.ok(met.collectorConfig.includeUrlPatterns.some((pattern) => new RegExp(pattern, "i").test("https://www.meteorology.gov.mv/single-news/132")));
assert.ok(met.collectorConfig.excludeUrlPatterns.includes("/downloads/"));
assert.equal(met.collectorConfig.autoCollect, false);
const metCap = registry.get("mv-met-cap-alerts");
assert.ok(metCap);
assert.equal(metCap.entityId, "mv-met");
assert.equal(metCap.collector, "rss");
assert.equal(metCap.collectorConfig.mode, "cap");
assert.equal(metCap.collectorConfig.autoCollect, false);
assert.equal(metCap.collectorConfig.feedUrl, "https://cap.meteorology.gov.mv/rss/alerts/");
assert.ok(metCap.tags.includes("cap"));
const metForecast = registry.get("mv-met-routine-forecast");
assert.ok(metForecast);
assert.equal(metForecast.entityId, "mv-met");
assert.equal(metForecast.collectorConfig.mode, "met_forecast");
assert.equal(metForecast.collectorConfig.autoCollect, false);
assert.equal(metForecast.collectorConfig.discoveryUrl, "https://meteorology.gov.mv/forecast");
assert.ok(metForecast.tags.includes("wave-height"));
const metTide = registry.get("mv-met-tide-predictions");
assert.ok(metTide);
assert.equal(metTide.entityId, "mv-met");
assert.equal(metTide.collectorConfig.mode, "met_tide");
assert.equal(metTide.collectorConfig.autoCollect, false);
assert.equal(metTide.collectorConfig.discoveryUrl, "https://meteorology.gov.mv/?pd=home");
assert.ok(metTide.tags.includes("tide"));
assert.equal(pack.sources.length, 40);
console.log(`source-pack tests passed (${pack.sources.length} sources)`);
